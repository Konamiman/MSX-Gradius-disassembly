; ----------------------------------------------------------------------
; UN MOTOR DE CUATRO SPRITES POR BICHO, SOLO PARA LA PANTALLA FIJA
; Este banco lleva su propio motorcillo, aparte del del juego: ocho fichas
; de ocho bytes en 0xE300, tres soltadores en 0xE500 y, para cada ficha,
; hasta CUATRO fichas de sprite seguidas en el buffer de 0xEC80. Cada
; bicho va asomando de sprite en sprite -el byte 5 cuenta cuantos lleva- y
; se mueve con un par de desplazamientos fijos que le tocan por su tipo.
