monta_la_pantalla:		; Limpia la RAM de trabajo, pone los tres soltadores y se copia a si mismo una rutina a 0xE710
	ld hl,0e300h		;a809   ; 0x800 bytes de 0xE300 en adelante, a cero
	ld de,0e301h		;a80c
	ld bc,00800h		;a80f
	ld (hl),000h		;a812
	ldir		;a814
	ld hl,0a881h		;a816   ; Los tres soltadores, de 0xA881 a 0xE500
	ld de,0e500h		;a819
	ld b,003h		;a81c   ; Tres fichas
L_A81E:
	push bc			;a81e
	ldi		;a81f   ; Cuatro bytes utiles de cada una
	inc de			;a821
	ldi		;a822
	ldi		;a824
	ldi		;a826
	inc de			;a828
	inc de			;a829
	inc de			;a82a
	pop bc			;a82b
	djnz L_A81E		;a82c
	ld a,010h		;a82e   ; 0xE700, 0xE702 y 0xE704: por donde empieza cada uno
	ld (0e700h),a		;a830
	ld a,018h		;a833
	ld (0e702h),a		;a835
	ld a,020h		;a838
	ld (0e704h),a		;a83a
	ld bc,00038h		;a83d   ; Y 0x38 bytes de rutina, copiados a 0xE710 para ejecutarlos desde la RAM
	ld hl,0a849h		;a840
	ld de,0e710h		;a843
	ldir		;a846
	ret			;a848

